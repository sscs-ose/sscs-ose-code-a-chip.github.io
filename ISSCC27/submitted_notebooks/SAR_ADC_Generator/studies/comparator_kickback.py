#!/usr/bin/env python3
"""Kickback of the StrongARM onto the floating top plate (single-ended SAR: CDAC on the + input, low-impedance Vcm
on the - input).  The comparator runs PRE clocks with the top plate (C_total of the CDAC, ideal cap) held, as after a
previous conversion; then the plate floats and the comparator makes N decisions, as in one conversion; the plate's drift before each decision is the error the
kickback adds.  Schematic and layout-extracted comparators.  Writes results/comparator_kickback.md.
Run inside IIC-OSIC-TOOLS:  python3 studies/comparator_kickback.py [bits ...]
"""
import json, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sargen import SarSpec, spice
from sargen.netlist import TR, load_strongarm_extraction, strongarm_subckt
from sargen.pdk import lib_line

PRE = 3       # comparator clocks before the plate floats (tail and pair in their running state)


def testbench(spec, c_top, sub, vd):
    tclk, n = spec.tclk, spec.bits + PRE
    return f"""* comparator kickback onto a floating top plate (generated by sargen)
{lib_line(spec.corner)}
.temp {spec.temp}
{sub}
.model swm sw vt=0.9 vh=0.1 ron=10 roff=1e15
Vdd vdd 0 {spec.vdd}
Vcm vcm 0 {spec.vcm}
Vs vs 0 {spec.vcm + vd:.9g}
Vsmp smp 0 PWL(0 1.8 {(PRE + 0.3) * tclk:.6g} 1.8 {(PRE + 0.3) * tclk + TR:.6g} 0)
Ssw vs top smp 0 swm
Ctop top 0 {c_top:.6g}
Vclk clk 0 PULSE(0 {spec.vdd} {0.5 * tclk:.6g} {TR} {TR} {0.45 * tclk - TR:.6g} {tclk:.6g})
Xc top vcm clk qp qn vdd 0 strongarm
.save v(top) v(qp)
.tran {tclk / 1000:.4g} {(n + 0.5) * tclk:.6g}
.control
set wr_singlescale
set wr_vecnames
run
wrdata wave.txt v(top) v(qp)
quit
.endc
.end
"""


def main(bits=(4, 6, 8)):
    md = ["| bits | comparator | input | top-plate drift after 1 decision [uV] | after N decisions [uV] "
          "| after N [LSB] |", "|---|---|---|---|---|---|"]
    res = {}
    for b in bits:
        spec, base = SarSpec(bits=b), Path(f"build/{b}bit")
        d = json.loads((base / "design.json").read_text())
        subs = {"schematic": strongarm_subckt(d["cmp"]),
                "layout": load_strongarm_extraction(base / "layout/pex/strongarm_pex.spice")}
        jobs, keys = [], []
        for name, sub in subs.items():
            for vd in (+spec.lsb / 2, -spec.lsb / 2):        # both decision directions
                keys.append((name, vd))
                jobs.append(dict(netlist=testbench(spec, d["cu"]["c_total"], sub, vd),
                                 workdir=base / "studies" / "kickback" / f"{name}_{'p' if vd > 0 else 'n'}"))
        for (name, vd), wd in zip(keys, spice.run_many(jobs)):
            w = spice.read_wrdata(Path(wd) / "wave.txt")
            t0 = (PRE + 0.45) * spec.tclk                              # sampled, plate floating, before the first clock
            edges = (PRE + np.arange(b) + 0.5) * spec.tclk - 0.02 * spec.tclk
            v0 = np.interp(t0, w["time"], w["top"])
            drift = np.interp(edges, w["time"], w["top"]) - v0
            # last decision's input: plate just before the final evaluation ends
            dn = np.interp((PRE + b - 0.5 + 0.44) * spec.tclk, w["time"], w["top"]) - v0
            res[f"{b} {name} {vd:+.4g}"] = dict(drift_uv=(drift * 1e6).tolist(), end_uv=dn * 1e6)
            md.append(f"| {b} | {name} | {'+' if vd > 0 else '-'}LSB/2 | {drift[1] * 1e6:+.1f} "
                      f"| {drift[-1] * 1e6:+.1f} | {drift[-1] / spec.lsb:+.4f} |")
            print(md[-1], flush=True)
    Path("results/comparator_kickback.json").write_text(json.dumps(res, indent=1))
    Path("results/comparator_kickback.md").write_text("\n".join(md) + "\n\nTop plate = ideal C_total of the CDAC "
                                                      "(no parasitics); Vcm ideal.\n")


if __name__ == "__main__":
    main(tuple(int(a) for a in sys.argv[1:]) or (4, 6, 8))
