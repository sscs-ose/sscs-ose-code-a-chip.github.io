"""Comparator input-referred noise, simulated in ngspice.

ngspice has no device noise in transient analysis: its only transient noise is TRNOISE on independent
sources (ngspice manual, 4.1.7 / 11.3.11).  So the StrongARM's dominant noise, the input pair's channel
thermal noise during integration, is injected as an equivalent differential input source, and the real
comparator integrates it:

1. A noiseless transient gives the input device's gm and the integration time T_int (clock edge until the
   latch PMOS turn on, i.e. the start of regeneration).
2. Input-referred PSD of the pair (one-sided): S_v = 2 * 4kT*gamma / gm  (both devices).
   Integrate-and-dump over T_int has a noise bandwidth of 1 / (2 T_int): sigma_est = sqrt(S_v / (2 T_int)).
3. TRNOISE(NA, NT) has a one-sided PSD of 2 NA^2 NT (checked against an RC filter), so NA = sqrt(S_v / (2 NT)).
4. Probability method (Razavi, "The Design of a Comparator", SSC Magazine 2020): comparators at fixed input
   offsets vd decide many times; P(decision) vs. vd is a Gaussian CDF whose sigma is the input-referred noise.

Latch and tail noise are not modelled (the tail is common mode; the latch is attenuated by the integration gain).
"""
import json
import math
from pathlib import Path
from statistics import NormalDist

import numpy as np

from . import spice
from .netlist import TR, strongarm_subckt
from .pdk import lib_line

K_B = 1.380649e-23
GAMMA = 1.0          # channel-noise factor; 2/3 in long-channel theory, ~1 is a common short-channel value
DEV = "msky130_fd_pr__nfet_01v8"


def _clock(spec, tclk):
    return f"Vclk clk 0 PULSE(0 {spec.vdd} {0.5 * tclk:.6g} {TR} {TR} {0.45 * tclk - TR:.6g} {tclk:.6g})"


def integration(spec, design, workdir) -> dict:
    """Noiseless decision at a small input: gm and drain current of the input device (means over the integration
    window) and T_int."""
    tclk, dev = spec.tclk, f"@m.xc.xmi1.{DEV}"
    vecs = f"v(clk) v(xc.outp) v(xc.outn) {dev}[gm] {dev}[id]"
    net = f"""* comparator integration window (generated by sargen)
{lib_line(spec.corner)}
.temp {spec.temp}
{strongarm_subckt(design['cmp'])}
Vdd vdd 0 {spec.vdd}
Vcm vcm 0 {spec.vcm}
Vp inp 0 {spec.vcm + spec.lsb / 64:.6g}
{_clock(spec, tclk)}
Xc inp vcm clk qp qn vdd 0 strongarm
.save {vecs}
.tran {tclk / 5000:.4g} {1.2 * tclk:.6g}
.control
set wr_singlescale
set wr_vecnames
run
wrdata wave.txt {vecs}
quit
.endc
.end
"""
    w = spice.read_wrdata(spice.run(net, Path(workdir)) / "wave.txt")
    t, op, on = w["time"], w["xc.outp"], w["xc.outn"]
    t0 = t[np.argmax(w["clk"] > spec.vdd / 2)]
    vthp = 0.45   # latch PMOS turn-on: outputs one |Vth,p| below vdd
    t1 = t[np.argmax((t > t0) & (np.minimum(op, on) < spec.vdd - vthp))]
    td = t[np.argmax((t > t0) & (np.abs(op - on) > spec.vdd / 2))]
    m = (t >= t0) & (t <= t1)
    gm = float(np.mean(w[f"{dev}[gm]"][m]))
    i_d = float(np.mean(np.abs(w[f"{dev}[id]"][m])))
    t_int = float(t1 - t0)
    s_v = 2 * 4 * K_B * (273.15 + spec.temp) * GAMMA / gm
    return dict(gm=gm, id=i_d, t_int=t_int, t_decide=float(td - t0), s_v=s_v, sigma_est=math.sqrt(s_v / (2 * t_int)))


def probability_testbench(spec, design, vds, na, nt, n_cycles) -> str:
    """One comparator per input offset vd, each with its own TRNOISE source in series with its + input."""
    tclk = spec.tclk
    inst = []
    for k, vd in enumerate(vds):
        inst += [f"Vn{k} inp{k} vp{k} DC 0 TRNOISE({na:.6g} {nt:.6g} 0 0)",
                 f"Vd{k} vp{k} 0 {spec.vcm + vd:.9g}",
                 f"Xc{k} inp{k} vcm clk qp{k} qn{k} vdd 0 strongarm"]
    saves = " ".join(f"v(qp{k})" for k in range(len(vds)))
    return f"""* comparator noise, probability method (generated by sargen)
{lib_line(spec.corner)}
.temp {spec.temp}
{strongarm_subckt(design['cmp'])}
Vdd vdd 0 {spec.vdd}
Vcm vcm 0 {spec.vcm}
{_clock(spec, tclk)}
""" + "\n".join(inst) + f"""
.save {saves}
.tran {nt:.4g} {(n_cycles + 0.5) * tclk:.6g}
.control
set wr_singlescale
set wr_vecnames
run
wrdata wave.txt {saves}
quit
.endc
.end
"""


def fit_sigma(vds, p_low):
    """Probit fit: P(qp low) = Phi((vd - mu) / sigma); points with 1 % < P < 99 % only."""
    pts = [(vd, NormalDist().inv_cdf(p)) for vd, p in zip(vds, p_low) if 0.01 < p < 0.99]
    if len(pts) < 2:
        return float("nan"), float("nan")
    x, z = np.array(pts).T
    slope, icpt = np.polyfit(x, z, 1)
    return float(1 / slope), float(-icpt / slope)


def measure(spec, design, workdir, n_cycles=300, levels=(-2, -1, -0.5, 0, 0.5, 1, 2), seed=1) -> dict:
    """Integration window -> injected noise -> probability-method sigma.  Results also in workdir/noise.json."""
    workdir = Path(workdir)
    r = integration(spec, design, workdir / "window")
    nt = r["t_int"] / 20                            # noise samples well inside the integration window
    na = math.sqrt(r["s_v"] / (2 * nt))
    vds = [lv * r["sigma_est"] for lv in levels]
    jobs = [dict(netlist=probability_testbench(spec, design, [vd], na, nt, n_cycles),
                 workdir=workdir / f"vd{k}", seed=seed + k) for k, vd in enumerate(vds)]
    tclk = spec.tclk
    ts = (np.arange(n_cycles) + 0.5) * tclk + 0.4 * tclk    # end of each evaluation phase
    p_low = []
    for wd in spice.run_many(jobs):
        w = spice.read_wrdata(Path(wd) / "wave.txt")
        q = np.interp(ts, w["time"], w["qp0"])
        p_low.append(float(np.mean(q < spec.vdd / 2)))
    sigma, mu = fit_sigma(vds, p_low)
    r.update(na=na, nt=nt, n_cycles=n_cycles, vds=vds, p_low=p_low, sigma_meas=sigma, mu=mu,
             lsb=spec.lsb, gamma=GAMMA)
    (workdir / "noise.json").write_text(json.dumps(r, indent=1))
    return r
