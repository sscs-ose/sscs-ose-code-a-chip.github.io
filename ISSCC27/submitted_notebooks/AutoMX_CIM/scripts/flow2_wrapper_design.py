"""Physical prototype topology shared by SPICE, layout and the RTL adapter.

The conditioner is a deliberately simple source-follower level shifter,
followed by a four-way differential TG mux. Its gain/CM/offset must be
measured. The ADC retains its own switched-capacitor VCM/reference circuit.
"""
from __future__ import annotations

from collections import Counter
from pathlib import Path
import re

from scripts import run_flow2_core_acquisition as core
from scripts import audit_flow2_adc_ip as ip

COND = "automx_cim_condition_mux_proto"
ANALOG = "automx_cim_readout_analog_proto"
TOP = "automx_cim_mixed_signal_proto"
COND_PINS = tuple([f"H{p}{c}" for c in range(4) for p in "PN"] +
                  [f"SEL{c}" for c in range(4)] + ["AINP", "AINN", "BIAS_MON", "VPWR", "VGND"])
PINS = (*core.CONTROLS, "PRE_B", "TRACK", *(f"SEL{c}" for c in range(4)),
        "ADC_RST_N", "ADC_START", "CLK_VCM", *(f"ADC_D{i}" for i in range(16)),
        "ADC_EOC", "ADC_EOC_OSR", "BIAS_MON", "VPWR", "VGND")


def conditioner():
    d = []
    def fet(name, kind, drain, gate, source):
        d.append({"name": name, "kind": kind, "nets": [drain, gate, source,
                  "VGND" if kind == "nfet" else "VPWR"]})
    # Diode-connected CMOS reference: two P devices versus one N device.
    # An actual loaded DC operating point is required; 0.9 V is not assumed.
    for i in range(2):
        fet(f"BIAS_P{i}", "pfet", "BIAS_MON", "BIAS_MON", "VPWR")
    fet("BIAS_N", "nfet", "BIAS_MON", "BIAS_MON", "VGND")
    for i in range(20):
        d.append({"name": f"BIAS_CAP{i}", "kind": "cap", "nets": ["BIAS_MON", "VGND"]})
    for c in range(4):
        sel, inv = f"SEL{c}", f"SELB{c}"
        fet(f"SEL_INV_N{c}", "nfet", inv, sel, "VGND")
        fet(f"SEL_INV_P{c}", "pfet", inv, sel, "VPWR")
        for p in "PN":
            held, buffered, out = f"H{p}{c}", f"BUF{p}{c}", "AIN" + p
            # Two parallel followers / one sink; input is insulated MOS gate.
            for i in range(2):
                fet(f"BUF_{p}{c}_{i}", "nfet", "VPWR", held, buffered)
            fet(f"SINK_{p}{c}", "nfet", buffered, "BIAS_MON", "VGND")
            fet(f"MUX_N_{p}{c}", "nfet", out, sel, buffered)
            fet(f"MUX_P_{p}{c}", "pfet", out, inv, buffered)
    return d


def schematic(cell=COND, pins=COND_PINS, devices=None):
    devices = conditioner() if devices is None else devices
    lines = ["* Real MOS/MIM prototype; gain, bias and common mode are uncharacterized.",
             f".subckt {cell} {' '.join(pins)}"]
    for d in devices:
        if d["kind"] == "cap":
            model, parameters = "sky130_fd_pr__cap_mim_m3_1", "W=4.2 L=4.2"
        else:
            model, parameters = f"sky130_fd_pr__{d['kind']}_01v8", "W=3.36 L=0.15"
        lines.append(f"X{d['name']} {' '.join(d['nets'])} {model} {parameters}")
    return "\n".join([*lines, f".ends {cell}", ""])


def expected_conditioner():
    c = Counter(d["kind"] for d in conditioner())
    return {"nfet": c["nfet"], "pfet": c["pfet"], "mim3": c["cap"]}


def adc_connections(pins):
    mapping = {"VDD": "VPWR", "VSS": "VGND", "inp_analog": "AINP", "inn_analog": "AINN",
        "rst_n": "ADC_RST_N", "start_conversion_in": "ADC_START", "clk_vcm": "CLK_VCM",
        "conversion_finished_out": "ADC_EOC", "conversion_finished_osr_out": "ADC_EOC_OSR"}
    mapping.update({f"result_out[{i}]": f"ADC_D{i}" for i in range(16)})
    # Digital configuration is hard-wired to the same no-AVG/no-OSR profile.
    for register, value in ((1, 0x0400), (2, 0x8421)):
        mapping.update({f"config_{register}_in[{i}]": "VPWR" if value & (1 << i) else "VGND" for i in range(16)})
    return [mapping.get(p, "ADC_INTERNAL_" + re.sub(r"[^A-Za-z0-9_]", "_", p)) for p in pins]


def reference(core_text, adc_lvs_flat):
    """ADC flat topology is generated by wire contraction for LVS only."""
    # All ADC internal/test ports get distinct parent-private nets.
    logical = re.sub(r"\n\s*\+", " ", adc_lvs_flat)
    m = re.search(r"(?im)^\.subckt\s+(\S+)\s+([^\n]+)", logical)
    if not m:
        raise ValueError("missing ADC LVS subcircuit")
    adc_cell, rc_pins = m[1], m[2].split()
    if len(rc_pins) != 81:
        raise ValueError("pinned ADC must retain all 81 RC formal ports")
    core_nodes = [p for p in core.PINS]
    lines = [re.sub(r"(?im)^\s*\.end\s*$", "", core_text), schematic(), adc_lvs_flat,
        f".subckt {ANALOG} {' '.join(PINS)}",
        f"XCORE {' '.join(core_nodes)} {core.CELL}",
        f"XCOND {' '.join(COND_PINS)} {COND}",
        f"XADC {' '.join(adc_connections(rc_pins))} {adc_cell}", f".ends {ANALOG}", ""]
    return "\n".join(lines)


def lef_ports(text):
    """Read rectangular ports, including multiple power shapes; never guess layers."""
    result = {}
    for m in re.finditer(r"(?ms)^\s*PIN\s+(\S+)\s*\n(.*?)^\s*END\s+\1\s*$", text):
        layer, shapes = None, []
        for line in m[2].splitlines():
            l = re.search(r"\bLAYER\s+(met[1-5])\s*;", line)
            if l:
                layer = l[1]
            r = re.search(r"\bRECT\s+([\d.eE+\-]+)\s+([\d.eE+\-]+)\s+([\d.eE+\-]+)\s+([\d.eE+\-]+)\s*;", line)
            if r and layer:
                xy = list(map(float, r.groups()))
                if xy[2] <= xy[0] or xy[3] <= xy[1]:
                    raise ValueError("invalid LEF rectangle")
                shapes.append((layer, xy))
        if not shapes or m[1] in result:
            raise ValueError("missing/duplicate LEF port geometry")
        result[m[1]] = shapes
    return result
