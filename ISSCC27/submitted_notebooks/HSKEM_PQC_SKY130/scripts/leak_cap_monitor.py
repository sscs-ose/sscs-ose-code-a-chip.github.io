"""Switched-capacitance monitor for a gate-level leakage trace (tb/tb_ntt_leak.sv with GLS_CAP).

Writes a Verilog module `leak_cap_mon` that watches every net of a routed netlist through hierarchical
references and, at every change of a net, adds that net's switched capacitance to an accumulator: the wire
capacitance of the extracted parasitics (SPEF total of the net) plus the input-pin capacitances of the cells
it drives (Liberty). The testbench reads and clears the accumulator once per clock, so a trace sample is the
capacitance switched in that cycle (proportional to the dynamic energy C V^2 of the cycle), in attofarads.
It replaces the register Hamming-distance proxy with every net of the layout weighted by its load.

usage: python3 leak_cap_monitor.py <6_final.v> <6_final.spef> <cells.lib> [<macro.lib> ...] --scope tb_ntt_leak.dut --out leak_cap_mon.sv
SPDX-License-Identifier: Apache-2.0
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import re


def liberty_pin_caps(paths: list[str]) -> dict[str, dict[str, float]]:
    """cell -> input pin -> capacitance [pF] (direction input, attribute capacitance)."""
    caps: dict[str, dict[str, float]] = collections.defaultdict(dict)
    for p in paths:
        cell = pin = None; direction = None; cap = None; depth = 0
        for line in open(p, errors="replace"):
            m = re.match(r"\s*cell\s*\(\s*\"?([\w$]+)\"?\s*\)", line)
            if m:
                cell = m[1]
            m = re.match(r"\s*pin\s*\(\s*\"?([\w$\[\]]+)\"?\s*\)", line)
            if m:
                pin, direction, cap = m[1], None, None
            m = re.match(r"\s*direction\s*:\s*\"?(\w+)\"?\s*;", line)
            if m and pin:
                direction = m[1]
            m = re.match(r"\s*capacitance\s*:\s*([\d.eE+-]+)\s*;", line)
            if m and pin and cap is None:
                cap = float(m[1])
            if pin and direction == "input" and cap is not None and cell:
                caps[cell][pin] = cap
    return caps


def spef_caps(path: str) -> dict[str, float]:
    """net name (as in SPEF, escapes removed) -> total wire capacitance [pF]."""
    name_map, out = {}, {}
    unit = 1.0
    for line in open(path, errors="replace"):
        if line.startswith("*C_UNIT"):
            v, u = line.split()[1:3]
            unit = float(v) * {"PF": 1.0, "FF": 1e-3, "NF": 1e3}[u.upper()]
        m = re.match(r"\*(\d+) (\S+)", line)
        if m and not line.startswith("*D_NET"):
            name_map["*" + m[1]] = m[2]
        if line.startswith("*D_NET"):
            _, n, c = line.split()[:3]
            out[name_map.get(n, n)] = float(c) * unit
    return out


def verilog_ref(spef_name: str) -> str:
    """SPEF net name -> Verilog reference below the scope: an escaped identifier for names that carry
    escaped brackets or dots (e.g. bank\\[0\\] -> \\bank[0] ), a bit select for bus ports (rdata[3])."""
    if "\\" in spef_name:
        return "\\" + spef_name.replace("\\", "") + " "
    return spef_name


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("netlist"); ap.add_argument("spef"); ap.add_argument("libs", nargs="+")
    ap.add_argument("--scope", required=True); ap.add_argument("--out", required=True)
    a = ap.parse_args()
    pin = liberty_pin_caps(a.libs)
    wire = spef_caps(a.spef)
    # input-pin load of every net, from the instance connections of the netlist
    load = collections.Counter()
    text = pathlib.Path(a.netlist).read_text()
    for m in re.finditer(r"^\s*(\w+)\s+(\\?\S+)\s*\((.*?)\);", text, re.M | re.S):
        cell = m[1]
        if cell not in pin:
            continue
        for pm in re.finditer(r"\.(\w+)\s*\(\s*(\\[^ ]+ |[\w\[\]]+)\s*\)", m[3]):
            p_, net = pm[1], pm[2].strip()
            if p_ in pin[cell]:
                load[net.lstrip("\\")] += pin[cell][p_]
    nets, total_wire, total_pin = [], 0.0, 0.0
    for n, c in wire.items():
        key = n.replace("\\", "")
        w = c + load.get(key, 0.0)
        total_wire += c; total_pin += load.get(key, 0.0)
        nets.append((verilog_ref(n), round(w * 1e6)))          # pF -> aF
    lines = ["// generated by scripts/leak_cap_monitor.py: switched capacitance per net [aF] (wire + input pins)",
             "`timescale 1ns/1ps", "module leak_cap_mon;", "    longint acc = 0;", "    longint toggles = 0;"]
    for ref, w in nets:
        if w <= 0:
            continue
        lines.append(f"    always @({a.scope}.{ref}) begin acc = acc + {w}; toggles = toggles + 1; end")
    lines.append("endmodule")
    pathlib.Path(a.out).write_text("\n".join(lines) + "\n")
    meta = {"nets": len(nets), "wire_cap_pf": total_wire, "pin_cap_pf": total_pin,
            "nets_with_pin_load": sum(1 for n in wire if load.get(n.replace("\\", ""), 0) > 0)}
    pathlib.Path(a.out).with_suffix(".json").write_text(json.dumps(meta, indent=1) + "\n")
    print(json.dumps(meta))


if __name__ == "__main__":
    main()
