"""Release identity: support-file digest and public copies of local reader links.

Reader documents regenerated by every release (Notebook, report, guides) link to the
submitted branch. Every other linked file must be pinned in ``public_sources.json`` to
an already-published commit whose bytes equal the local file; building fails otherwise.
Refresh pins after publishing changed evidence with
``python -B -m presentation.release_identity --pin`` (requires Git and the fork remote).
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
from pathlib import Path, PurePosixPath
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
PREFIX = "ISSCC27/submitted_notebooks/comparator_atlas"
BRANCH = "wlhsu0827-comparator-atlas-isscc27"
FORK = "WLHsu0827/sscs-ose-code-a-chip.github.io"
NOTEBOOK = "Comparator_Atlas.ipynb"
CHECKSUMS = "entry_checksums.json"
MANIFEST = ROOT / "presentation/public_sources.json"
PLACEHOLDER = "__SUPPORT_RELEASE__"
# Regenerated with each release, so they can only follow the submitted branch.
READER_DOCUMENTS = frozenset({NOTEBOOK, "README.md", "REVIEWER_GUIDE.md", "REPRODUCIBILITY.md",
                              "results/study/report.html"})
EXCLUDED_PARTS = frozenset({"__pycache__", ".pytest_cache"})


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def release_files(root: Path = ROOT) -> dict[str, str]:
    """The sealed file map written to entry_checksums.json."""
    return {p.relative_to(root).as_posix(): sha256(p) for p in sorted(root.rglob("*"))
            if p.is_file() and p.name != CHECKSUMS and not EXCLUDED_PARTS & set(p.parts)}


def support_digest(files: dict[str, str]) -> str:
    """Identity of every sealed file except the editable Notebook; the bootstrap repeats this."""
    support = {name: value for name, value in files.items() if name != NOTEBOOK}
    canonical = json.dumps(support, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode()).hexdigest()


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_bytes())


def blob_url(reference: str, path: str, fragment: str = "") -> str:
    return f"https://github.com/{FORK}/blob/{reference}/{PREFIX}/{path}" + (
        f"#{fragment}" if fragment else "")


def resolve(target: str, base: str = "") -> tuple[str, str]:
    """Entry-relative path and fragment of a relative link written inside ``base``."""
    path, _, fragment = target.partition("#")
    parts = []
    for part in (PurePosixPath(base) / path).parts:
        if part == "..":
            if not parts:
                raise ValueError(f"Link leaves the entry: {target} from {base or '.'}")
            parts.pop()
        elif part != ".":
            parts.append(part)
    return "/".join(parts), fragment


def public_url(path: str, fragment: str = "", manifest: dict | None = None) -> tuple[str, str]:
    """Public URL and the reference it is bound to; pinned bytes are checked first."""
    if path in READER_DOCUMENTS:
        return blob_url(BRANCH, path, fragment), BRANCH
    pins = (manifest or load_manifest())["files"]
    if path not in pins:
        raise KeyError(f"No published pin for linked file {path}; run release_identity --pin")
    pin = pins[path]
    if sha256(ROOT / path) != pin["sha256"]:
        raise ValueError(f"{path} differs from its pinned public copy {pin['commit'][:12]}; "
                         "publish the change and re-pin it")
    return blob_url(pin["commit"], path, fragment), pin["commit"]


def is_relative(target: str) -> bool:
    return not re.match(r"^(?:[a-z][a-z0-9+.-]*:|#|/)", target, re.I)


ANCHOR = re.compile(r'<a href="([^"]+)">(.*?)</a>', re.S)


def add_public_copies_html(document: str, base: str) -> str:
    """Follow every relative anchor outside scripts with its public copy."""
    manifest = load_manifest()

    def anchor(match):
        target = html.unescape(match.group(1))
        if not is_relative(target):
            return match.group()
        url, reference = public_url(*resolve(target, base), manifest)
        label = "submitted branch" if reference == BRANCH else f"commit {reference[:7]}"
        return (match.group() + f' <a class="public-copy" href="{html.escape(url, quote=True)}"'
                f' title="Public copy ({label})">(public copy)</a>')

    pieces = re.split(r"(<script\b.*?</script>)", document, flags=re.S)
    return "".join(piece if piece.startswith("<script") else ANCHOR.sub(anchor, piece)
                   for piece in pieces)


MARKDOWN_LINK = re.compile(r"(?<!!)\[([^\]]+)\]\(([^)\s]+)\)")


def add_public_copies_markdown(text: str) -> str:
    """Notebook-only and Colab readers lack the entry folder; give each relative link a public copy."""
    manifest = load_manifest()

    def link(match):
        if not is_relative(match.group(2)):
            return match.group()
        url, _ = public_url(*resolve(match.group(2)), manifest)
        return match.group() + f" ([public copy]({url}))"

    return MARKDOWN_LINK.sub(link, text)


def source_table_links(base: str = "results/study") -> dict[str, dict]:
    """Pinned public copies of the measurement tables named by decision records."""
    manifest = load_manifest()
    links = {}
    for name in ("verified_measurements.csv", "professional/measurements.csv"):
        url, commit = public_url(resolve(name, base)[0], manifest=manifest)
        links[name] = {"url": url, "commit": commit}
    return links


def _git(*args: str, text: bool = True):
    top = subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "--show-toplevel"],
                                  text=True).strip()
    output = subprocess.check_output(["git", "-C", top, *args], text=text)
    return output.strip() if text else output


def pin(paths: list[str], remote_ref: str) -> None:
    """Record, for each file, the latest published commit holding exactly its local bytes."""
    previous = load_manifest()["files"] if MANIFEST.is_file() else {}
    files = {}
    for path in sorted(set(paths) | set(previous)):
        if path in READER_DOCUMENTS:
            raise ValueError(f"{path} follows the submitted branch and cannot be pinned")
        local = ROOT / path
        commit = _git("log", "-1", "--format=%H", remote_ref, "--", f"{PREFIX}/{path}")
        if not commit:
            raise ValueError(f"{path} has never been published on {remote_ref}")
        published = _git("cat-file", "blob", f"{commit}:{PREFIX}/{path}", text=False)
        if hashlib.sha256(published).hexdigest() != sha256(local):
            raise ValueError(f"Local {path} is not yet published on {remote_ref}")
        files[path] = {"commit": commit, "sha256": sha256(local)}
    MANIFEST.write_text(json.dumps({
        "schema": 1, "repository": FORK, "entry": PREFIX, "branch": BRANCH,
        "rule": "Each linked evidence file is pinned to a published commit whose bytes equal the "
                "local file; reader documents follow the submitted branch.",
        "files": files,
    }, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pin", nargs="*", metavar="PATH", default=None,
                        help="Entry-relative files to (re)pin; existing pins are refreshed too")
    parser.add_argument("--remote-ref", default=f"refs/remotes/fork/{BRANCH}")
    args = parser.parse_args()
    if args.pin is not None:
        pin(args.pin, args.remote_ref)
    files = release_files()
    print(json.dumps({"pins": len(load_manifest()["files"]),
                      "support_digest": support_digest(files)}, indent=2))


if __name__ == "__main__":
    main()
