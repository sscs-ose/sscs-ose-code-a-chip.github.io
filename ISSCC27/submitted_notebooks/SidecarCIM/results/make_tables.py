def md_table(head, rows):
    s = "| " + " | ".join(head) + " |\n"
    s += "| " + " | ".join(["---"] * len(head)) + " |\n"
    for r in rows:
        s += "| " + " | ".join(str(x) for x in r) + " |\n"
    return s


def pm(d, se):
    if d is None:
        return ""
    return "%+.2f ± %.2f" % (d, se) if se is not None else "%+.2f" % d


def label(r):
    return r["scheme"] + (" (%s)" % r["alias"] if r["alias"] else "")


def accuracy_tables(rows):
    keys = list(rows[0].keys())
    with open(os.path.join(H, "table_accuracy.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)
    head = ["scheme", "k", "tile scale", "w-clip", "a-clip",
            "PPL (12/24 layers)", "increase over FP32 ± SE",
            "layer-0 only increase ± SE"]
    md = "# Accuracy tables\n\nGenerated by `results/make_tables.py` from " \
         "`python/out/{novelty,qwen,accuracy}.json`. Increase = " \
         "perplexity minus FP32 perplexity on WikiText-2 test; SE is the " \
         "paired standard error over eval windows.\n"
    for model, fpkey in (("GPT-2", None), ("Qwen2.5-0.5B", None)):
        sel = [r for r in rows if r["model"] == model and
               r["eval_tokens"] == 8192]
        md += "\n## %s, 8192-token test (FP32 PPL %.2f)\n\n" % (
            model, sel[0]["ppl_fp32"])
        md += md_table(head, [
            [label(r), r["k"], "yes" if r["tile_scale"] else "no",
             "yes" if r["wclip"] else "no", "yes" if r["aclip"] else "no",
             f(r["ppl_all"]), pm(r["d_all"], r["se_all"]),
             pm(r["d_layer0"], r["se_layer0"])] for r in sel])
    sel = [r for r in rows if r["model"] == "GPT-2" and
           r["eval_tokens"] == 2048]
    md += "\n## GPT-2, 2048-token test, all variants (FP32 PPL %.2f; " \
          "single run, no SE saved)\n\n" % sel[0]["ppl_fp32"]
    head2 = ["scheme", "k", "slot rule", "tile", "w-clip", "a-clip",
             "budget-constrained migration", "PPL (12 layers)",
             "increase over FP32", "layer-0 only increase"]
    md += md_table(head2, [
        [label(r), r["k"], r["slot_rule"],
         "yes" if r["tile_scale"] else "no", "yes" if r["wclip"] else "no",
         "yes" if r["aclip"] else "no", "yes" if r["budget_mig"] else "no",
         f(r["ppl_all"]), "%+.2f" % r["d_all"], "%+.2f" % r["d_layer0"]]
        for r in sel])
    with open(os.path.join(H, "table_accuracy.md"), "w") as fh:
        fh.write(md)


def bitplane_table():
    b = pc.load("bitplane.json")
    fm = b["formats"]
    names = ["raw", "sm", "sm3", "tc", "tcse"]
    md = "# Bit-plane skip study (GPT-2 c_fc, 4-bit activation codes)\n\n"
    md += "Generated by `results/make_tables.py` from " \
          "`python/out/bitplane.json` (%s; calibration %s).\n\n" % (
              b["eval"], b["calib"])
    md += "Mean bit-plane cycles per 32×8 MVM (raw = ABITS = 4; lower " \
          "means planes were skipped). Formats:\n\n"
    for n in names:
        md += "- `%s`: %s\n" % (n, fm[n])
    head = ["encoding", "scope", "% codes at zero point"] + names
    rows = []
    for enc, lab in (("final_alpha1.0", "with migration (alpha 1.0)"),
                     ("nomig", "no migration")):
        for sc, sl in (("h0", "layer h.0"), ("all12", "all 12 layers")):
            d = b["enc"][enc][sc]
            rows.append([lab, sl, "%.1f" % d["pct_x_eq_zp"]] +
                        ["%.2f" % d[n]["cycles"] for n in names])
    md += "\n" + md_table(head, rows)
    d = b["enc"]["final_alpha1.0"]["all12"]
    md += "\nFraction of 32-row tiles whose top bit-plane is entirely " \
          "skippable, with migration, all 12 layers: sign-magnitude %.1f%%," \
          " 3-bit sign-magnitude %.1f%%, two's complement %.1f%%.\n" % (
              100 * d["sm"]["skip"][0], 100 * d["sm3"]["skip"][0],
              100 * d["tc"]["skip"][0])
    md += "\nAfter migration only %.1f%% of activation codes sit at the " \
          "zero point (all layers), so the only encoding that skips cycles " \
          "is sign-magnitude of (x - zero point), at %.2f cycles out of 4. " \
          "Two's complement skips almost nothing (%.2f). Large savings " \
          "(%.2f cycles, sign-magnitude) appear only without migration, " \
          "where accuracy has already collapsed (see table_accuracy.md). " \
          "We did not cost the sign-magnitude recoding in hardware and did " \
          "not build skipping.\n" % (
              d["pct_x_eq_zp"], d["sm"]["cycles"], d["tc"]["cycles"],
              b["enc"]["nomig"]["all12"]["sm"]["cycles"])
    with open(os.path.join(H, "table_bitplane.md"), "w") as fh:
        fh.write(md)


