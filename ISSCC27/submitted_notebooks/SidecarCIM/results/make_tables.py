def scaling_finding():
    """Finding from scaling.csv (synthesis, cg=1) and tile_scaling.json."""
    import ppa_data as pdd
    import re as re_
    a = {}
    for r in pdd.load_csv("scaling.csv"):
        if r["stage"] == "synth" and r.get("cg", "0") == "1":
            a[(r["design"], int(r["n_in"]),
               int(r["k"]) if r["k"] else 0)] = float(r["cell_area_um2"])
    ts = pc.load("tile_scaling.json")
    fr = ts["frontier"]
    thr = float(re_.search(r"\|t\| < (\d+(?:\.\d+)?)", fr["rule"]).group(1))
    t = {m: {(r["R"], r["k"]): (r["vs_ref"]["t"] if r["vs_ref"] else 0.0)
             for r in ts["tables"][m]["rows"] if r["k"]}
         for m in ("gpt2", "qwen")}
    Rs = sorted(int(x) for x in fr["by_R"])
    sp = pc.spec()
    k0, n0 = sp["outlier"]["budget_per_output"], sp["array"]["n_inputs"]

    def ratio(R, k):
        return a[("sidecarcim_top", R, k)] / a[("dcim_core", R, 0)]

    def ok(R, k):
        return all(abs(t[m][(R, k)]) < thr or t[m][(R, k)] <= -thr
                   for m in t)
    fixed = ", ".join("%d: %.2f%s" % (R, ratio(R, k0),
                                      "" if ok(R, k0) else " (fails)")
                      for R in Rs)
    first_fail = min(R for R in Rs if not ok(R, k0))
    scaled = ", ".join("%d: %.2f (k=%d)" % (R, ratio(R, k0 * R // n0),
                                            k0 * R // n0) for R in Rs)
    front = ", ".join("%d: %.2f (k=%d)" % (
        R, ratio(R, fr["by_R"][str(R)]["k_min"]),
        fr["by_R"][str(R)]["k_min"]) for R in Rs)
    Rm = Rs[-1]
    km = fr["by_R"][str(Rm)]["k_min"]
    head = ("In synthesis, at equal accuracy, the sidecar overhead goes "
            "from %.2fx at %d rows to %.2fx at %d rows. Fixed k = %d would "
            "give %.2fx, but it loses accuracy" % (
                ratio(n0, k0), n0, ratio(Rm, km), Rm, k0, ratio(Rm, k0)))
    return (
        "%s. Storage is clock-gated, and the accuracy comes from the "
        "8-window evaluation, one run per point. The synthesized area of the sidecar macro over a dense "
        "4-bit array at fixed k = %d is, by rows, %s. Fixed k = %d fails "
        "accuracy from %d rows on (t against the %d-row design at %d "
        "rows: GPT-2 %.2f, Qwen %.2f). Scaling k with the height keeps "
        "accuracy but costs %s. The fewest k that are not significantly "
        "worse than the built design on both models (|t| < %g over 8 "
        "windows) give %s; at %d rows k = %d passes only marginally (t "
        "%.2f and %.2f) (`fig_scaling`, `scaling.csv`, "
        "`tile_scaling.json`)." % (
            head, k0, fixed, k0, first_fail, n0, Rm, t["gpt2"][(Rm, k0)],
            t["qwen"][(Rm, k0)], scaled, thr, front, Rm, km,
            t["gpt2"][(Rm, km)], t["qwen"][(Rm, km)]))


