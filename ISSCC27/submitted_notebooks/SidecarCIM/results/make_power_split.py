"""table_power_split.{csv,md}: OpenSTA power group split per FF design.

Parsed from the real-activity report of the run named in results/ppa.csv:
<run>/power_real.rpt (gate-level VCD, clock-gated runs) or, if absent,
<run>/power_vcd.rpt. Post-layout estimates.

Without run directories (e.g. a CI copy) the saved table_power_split.csv
is the artifact: its rows are kept if their total still matches ppa.csv,
and only the Markdown is rebuilt from them.
"""
import csv
import os
import re

import plot_common as pc
import ppa_data as pd

DESIGNS = [("4-bit DCIM (FF)", "dcim_core_ff"),
           ("SidecarCIM (FF, merge reg., 3-bit S)", pd.HEAD),
           ("SidecarCIM, no merge reg. (FF)", "sidecarcim_top_ff"),
           ("SidecarCIM parallel (FF)", "sidecarcim_top_ff_par"),
           ("Dense W6A4 (FF)", "dcim_w6a4_ff"),
           ("Dense W8A4 (FF)", "dcim_w8a4_ff"),
           ("8-bit DCIM (FF)", "dcim_8bit_ff"),
           ("MAC baseline", "mac_baseline")]
GROUPS = ["Sequential", "Clock", "Combinational", "Macro", "Pad"]
REPORTS = ("power_real.rpt", "power_vcd.rpt")
ROW = re.compile(r"^(Sequential|Combinational|Clock|Macro|Pad|Total)\s+"
                 r"(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+([\d.]+)%")
CSV = os.path.join(pc.HERE, "table_power_split.csv")
TOL_MW = 0.051   # ppa.csv keeps power to 3 significant digits


def parse(path):
    out = {n: (0.0, 0.0) for n in GROUPS}
    with open(path) as f:
        for line in f:
            m = ROW.match(line)
            if m:
                out[m.group(1)] = (float(m.group(5)) * 1e3,
                                   float(m.group(6)))
    return out


def report(run_dir):
    for name in REPORTS:
        path = os.path.join(pc.ROOT, run_dir, name)
        if os.path.exists(path):
            return path
    return None


def saved_rows():
    if not os.path.exists(CSV):
        return {}
    with open(CSV) as f:
        return {r["design"]: r for r in csv.DictReader(f)}


def main():
    p = pd.ppa()
    old = saved_rows()
    rows = []
    for label, key in DESIGNS:
        if key not in p:
            continue
        path = report(p[key]["run_dir"])
        if path is None:
            r = old.get(key)
            assert r is not None and abs(float(r["total_mw"]) -
                                         p[key]["power_mw_est"]) < TOL_MW, \
                "%s: no power report in %s and saved CSV is stale" % (
                    key, p[key]["run_dir"])
            print("make_power_split: %s kept from saved CSV" % key)
            rows.append(r)
            continue
        g = parse(path)
        assert abs(g["Total"][0] - p[key]["power_mw_est"]) < TOL_MW, \
            (key, g["Total"][0], p[key]["power_mw_est"])
        r = {"circuit": label, "design": key,
             "total_mw": round(g["Total"][0], 4),
             "report_total_matches_ppa_csv_mw": p[key]["power_mw_est"],
             "report": os.path.relpath(path, pc.ROOT)}
        for n in GROUPS:
            r[n.lower() + "_mw"] = round(g[n][0], 4)
            r[n.lower() + "_pct"] = g[n][1]
        rows.append(r)
    keys = ["circuit", "design", "total_mw", "report_total_matches_ppa_csv_mw"]
    for n in GROUPS:
        keys += [n.lower() + "_mw", n.lower() + "_pct"]
    keys.append("report")
    with open(CSV, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=keys, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    from make_tables import md_table
    head = ["circuit", "total (mW)"] + ["%s mW (%%)" % n for n in GROUPS]
    md = "# Power split by cell group (post-layout estimate)\n\n"
    md += "Generated by `results/make_power_split.py` from the OpenSTA " \
          "real-activity report of each design's final run (run " \
          "directories from `results/ppa.csv`; report file in the CSV " \
          "column `report`): `power_real.rpt` (gate-level VCD of the " \
          "clock-gated netlist, real GPT-2 stimulus) or `power_vcd.rpt`. " \
          "Clock-gated storage, %g ns clock. Percentages are of the report " \
          "total; the MAC baseline is included for completeness.\n\n" % (
              p[DESIGNS[0][1]]["clock_period_ns"])
    md += md_table(head, [[r["circuit"], "%.2f" % float(r["total_mw"])] + [
        "%.2f (%.1f%%)" % (float(r[n.lower() + "_mw"]),
                           float(r[n.lower() + "_pct"]))
        for n in GROUPS] for r in rows])
    with open(os.path.join(pc.HERE, "table_power_split.md"), "w",
              encoding="utf8") as fh:
        fh.write(md)
    print("wrote table_power_split")


if __name__ == "__main__":
    main()
