"""Trusted Linux subprocess supervisor for the fixed S11 adapter (no shell).

The request is generated by physical_tools, never by an LLM. A retained cancel
file or timeout terminates the complete Linux process group, including tools
inside the AppImage. Raw stdout/stderr and the actual exit are retained.
"""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import signal
import subprocess
import time

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('request',type=Path)
    args=parser.parse_args()
    request=json.loads(args.request.read_text(encoding='utf-8'))
    assert request['version']=='hullcirq-physical-worker-v1'
    argv=request['argv']
    assert isinstance(argv,list) and all(type(x) is str and '\x00' not in x for x in argv)
    assert argv[0].startswith('/') and argv[0].endswith('librelane-devshell-x86_64.AppImage')
    assert argv[1] in ('librelane','python3')
    root=args.request.resolve().parent
    started=time.monotonic(); status='Completed'
    with (root/'stdout.log').open('wb') as stdout,(root/'stderr.log').open('wb') as stderr:
        process=subprocess.Popen(argv,cwd=root,stdout=stdout,stderr=stderr,start_new_session=True,shell=False)
        while process.poll() is None:
            cancelled=(root/'cancel.request').exists()
            if cancelled or time.monotonic()-started>request['timeout_seconds']:
                status='Cancelled' if cancelled else 'Timeout'
                os.killpg(process.pid,signal.SIGTERM)
                try:process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    os.killpg(process.pid,signal.SIGKILL);process.wait()
                break
            time.sleep(.2)
    result={'status':status,'executed':True,'exit_code':process.returncode,'argv':argv,'elapsed_seconds':time.monotonic()-started,'process_group':process.pid,'whole_process_group_terminated_on_cancel':status in ('Cancelled','Timeout')}
    (root/'process-result.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    return 0

if __name__=='__main__':raise SystemExit(main())
