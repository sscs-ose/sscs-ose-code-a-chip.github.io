#!/usr/bin/env python3
"""tb/tb_row_ctrl.v (row_ctrl 판 testbench, 사본) → tb/tb_row_blk.v + tb/rb_macro_stubs.v

row_blk 은 decoder 출력 12 × 106 이 블록 핀이 아니라 매크로 ctl·ctlb 로만 간다. 그래서 같은 검사를 하되
'got' 을 dut 안 매크로 인스턴스의 ctl·ctlb 에서 읽는다 (계층 참조 dut.rm<r>_<XT1…>.ctl).
어느 매크로의 ctl·ctlb 가 어느 decoder 출력인지는 chip_lib.py ROWM 에서 읽는다 (mk_netlist.rowm_instances) →
매크로 모형 = 포트만 있는 빈 module (아날로그 a·b 는 검사 대상이 아님 → check_rb.py 가 netlist 로 따로 봄).
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from mk_netlist import NR, INPUTS, rowm_instances   # noqa: E402

_, insts = rowm_instances()
src = (HERE / 'tb' / 'tb_row_ctrl.v').read_text()
m = re.search(r'\n\s*row_ctrl dut \(.*?\);\n', src, re.S)
assert m, 'tb_row_ctrl.v 의 dut 를 못 찾음'
L = ['', '    // row_blk: 아날로그 핀은 비워 둠 (매크로 모형이 빈 module)',
     '    wire vw, vwl, vzero, R1, R2;', '    wire [NR-1:0] row, wl;',
     '    row_blk dut (' + ', '.join(f'.{p}({p})' for p in INPUTS + ['vw', 'vwl', 'vzero', 'R1', 'R2', 'row', 'wl']) + ');',
     '    // decoder 출력 = 매크로 ctl (nfet 게이트) / ctlb (pfet 게이트) — chip_lib.py ROWM 연결 그대로']
n = 0
for r in range(NR):
    for name, cell, pins in insts:
        L.append(f'    assign {pins["ctl"]}[{r}] = dut.rm{r}_{name}.ctl;')
        L.append(f'    assign {pins["ctlb"]}[{r}] = dut.rm{r}_{name}.ctlb;')
        n += 2
assert n == 12 * NR
tb = src[:m.start()] + '\n'.join(L) + '\n' + src[m.end():]
tb = tb.replace('module tb_row_ctrl;', 'module tb_row_blk;', 1)
tb = ('// tb_row_blk.v — GENERATED by mk_tb_rb.py from tb/tb_row_ctrl.v (손으로 고치지 말 것)\n'
      '//   row_ctrl 판과 같은 검사, 단 decoder 출력을 매크로 ctl·ctlb 에서 읽음\n') + tb
(HERE / 'tb' / 'tb_row_blk.v').write_text(tb)
S = ['// rb_macro_stubs.v — GENERATED by mk_tb_rb.py: 매크로 포트만 (게이트 시뮬에서 ctl·ctlb 를 읽는 자리)']
for cell, ports in (('rb_tgw_n20', 'a, b'), ('rb_tg_n2', 'a, b'), ('rb_tg_n2_av', 'b'), ('rb_tg_n2_as', 'b')):
    S.append(f'module {cell} ({ports}, ctl, ctlb);\n    inout {ports};\n    input ctl, ctlb;\nendmodule')
(HERE / 'tb' / 'rb_macro_stubs.v').write_text('\n'.join(S) + '\n')
print(f'tb/tb_row_blk.v: {n} decoder outputs read at macro pins')
