#!/usr/bin/env python3
"""chip_lib.py 의 ROWL subckt (SPICE 줄, NAND2·NOR2·INV) → 게이트 그대로 옮긴 Verilog 기준 모형 tb/ref_rowl.v.
RTL (rtl/rowl.v) 과 따로 만든 모형이라, testbench 가 둘을 맞대 보면 RTL 이 검증된 트랜지스터 netlist 의 논리와 같은지 확인된다.
real_circuit/ 은 읽기만 한다 (python -B: __pycache__ 를 만들지 않음).
쓰임: python3 -B gen_ref_rowl.py   (로컬, real_circuit 경로가 있는 곳)
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
H = Path(__file__).resolve().parent
RC = H.parents[1] / 'real_circuit'                      # ep_dr/real_circuit
sys.path.insert(0, str(RC))
import chip_lib                                          # noqa: E402

PRIM = {'NAND2': ('nand', 2), 'NOR2': ('nor', 2), 'INV': ('not', 1)}
hdr, *body = chip_lib.ROWL
assert hdr.startswith('.subckt ROWL') and body[-1].startswith('.ends')
ports = hdr.split()[2:]
assert ports[-2:] == ['vdd', 'vss']
ports = ports[:-2]
ins, outs = ports[:7], ports[7:]                          # t sel_en PROG VER SENSE READb WRANY | 12 출력
driven, gates = {}, []
for ln in body[:-1]:
    t = ln.split()
    cell = t[-1]
    prim, nin = PRIM[cell]
    a, y = t[1:1 + nin], t[1 + nin]
    assert t[2 + nin:4 + nin] == ['vdd', 'vss'], ln
    assert y not in driven, f'{y} 를 두 번 구동: {ln}'
    driven[y] = ln
    gates.append(f'    {prim} {t[0]} ({y}, {", ".join(a)});')
for o in outs:
    assert o in driven, f'출력 {o} 를 구동하는 게이트가 없음'
used = {n for g in gates for n in g[g.index('(') + 1:g.rindex(')')].replace(',', ' ').split()}
internal = sorted(used - set(ins) - set(outs))
for n in internal:
    assert n in driven, f'내부 노드 {n} 이 떠 있음'
v = ['// ref_rowl.v — GENERATED by tb/gen_ref_rowl.py from real_circuit/chip_lib.py ROWL (손으로 고치지 말 것)',
     '// SPICE 게이트 (NAND2 / NOR2 / INV) 를 Verilog 기본 게이트로 하나씩 옮김',
     f'module ref_rowl ({", ".join(ports)});',
     f'    input {", ".join(ins)};',
     f'    output {", ".join(outs)};',
     f'    wire {", ".join(internal)};'] + gates + ['endmodule', '']
(H / 'ref_rowl.v').write_text('\n'.join(v))
print(f'ref_rowl.v: 게이트 {len(gates)}, 입력 {len(ins)}, 출력 {len(outs)}, 내부 노드 {len(internal)}')
