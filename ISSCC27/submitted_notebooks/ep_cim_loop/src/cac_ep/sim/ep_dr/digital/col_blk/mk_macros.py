#!/usr/bin/env python3
"""col_blk 이 쓰는 매크로 묶음을 macros/ 에 만든다 (원본은 읽기만).
  - cb_tg_n2·cb_tgw_n20 = layout/blocks/tg_n2·tgw_n20 의 '원점 맞춘' 사본.
    원본 LEF 는 ORIGIN 0.460 0.185 인데 RECT 는 이미 bbox 왼쪽 아래 기준이라, LEF 대로 놓으면 ORIGIN 만큼 두 번 밀린다.
    → GDS 를 (+0.460, +0.185) 옮겨 bbox 를 (0,0) 에 두고 LEF ORIGIN 0 0 (RECT 는 그대로). 셀 이름 앞에 cb_ (다른 블록의 tg_n2 와 GDS 이름이 겹치지 않게).
    도형은 옮기기만 하고 바꾸지 않는다. CDL 은 subckt 이름만 바꿈.
  - clamp_d2r = digital/macros/clamp_d2r (다른 agent 의 δ clamp, 이미 ORIGIN 0 0) 그대로 복사본 (gds·lef·cdl, 10/28 01:22 판).
쓰임: /home/dave/work/projects/sern_hog_classab_opamp/sim/.venv/bin/python mk_macros.py
"""
import re
import shutil
from pathlib import Path

import klayout.db as db

H = Path(__file__).resolve().parent
M = H / 'macros'
SRC = H.parents[1] / 'layout' / 'blocks'                 # ep_dr/layout/blocks (읽기만)
CLAMP = H.parent / 'macros'                              # ep_dr/digital/macros (다른 agent, 읽기만)
M.mkdir(exist_ok=True)

for name in ('tg_n2', 'tgw_n20'):
    new = 'cb_' + name
    lef = (SRC / f'{name}.lef').read_text()
    m = re.search(r'ORIGIN\s+([\d.]+)\s+([\d.]+)', lef)
    ox, oy = float(m.group(1)), float(m.group(2))
    ly = db.Layout(); ly.read(str(SRC / f'{name}.gds'))
    assert len(ly.top_cells()) == 1
    c = ly.top_cells()[0]
    bb = c.dbbox()
    assert abs(bb.left + ox) < 1e-6 and abs(bb.bottom + oy) < 1e-6, (bb, ox, oy)   # GDS bbox 왼쪽 아래 = −ORIGIN
    c.transform(db.DCplxTrans(1.0, 0, False, db.DVector(ox, oy)))                  # 도형 (+ox, +oy)
    c.name = new
    nb = c.dbbox()
    ly.write(str(M / f'{new}.gds'))
    lef2 = lef.replace(f'MACRO {name}', f'MACRO {new}').replace(f'END {name}', f'END {new}')
    lef2 = re.sub(r'ORIGIN\s+[\d.]+\s+[\d.]+\s*;', 'ORIGIN 0.000 0.000 ;', lef2)
    sz = re.search(r'SIZE\s+([\d.]+)\s+BY\s+([\d.]+)', lef2)
    assert abs(float(sz.group(1)) - nb.width()) < 1e-6 and abs(float(sz.group(2)) - nb.height()) < 1e-6
    # LEF 핀 RECT 와 GDS 핀 글자 자리 대조 (원점 맞춤 확인): 핀 VSS·VDD (met1 rail) 이 GDS met1 안에 있는지
    m1 = db.Region(c.begin_shapes_rec(ly.layer(68, 20)))
    for pn in ('VSS', 'VDD', 'ctl', 'ctlb'):
        r = re.search(rf'PIN {pn}\s.*?RECT\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)', lef2, re.S)
        x0, y0, x1, y1 = (int(round(float(v) * 1000)) for v in r.groups())
        assert (db.Region(db.Box(x0, y0, x1, y1)) - m1).is_empty(), f'{new} {pn} LEF rect not on GDS met1'
    (M / f'{new}.lef').write_text(lef2)
    cdl = (SRC / f'{name}.cdl').read_text()
    cdl = re.sub(rf'^\.subckt {name}\b', f'.subckt {new}', cdl, flags=re.M | re.I)
    cdl = re.sub(rf'^\.ends {name}\b', f'.ends {new}', cdl, flags=re.M | re.I)
    (M / f'{new}.cdl').write_text(cdl)
    print(f'{new}: bbox {nb}, LEF ORIGIN 0 0 (원본 {ox} {oy}), 핀 RECT ↔ GDS met1 일치')

for ext in ('gds', 'lef', 'cdl'):
    shutil.copy2(CLAMP / f'clamp_d2r.{ext}', M / f'clamp_d2r.{ext}')
shutil.copy2(CLAMP / 'sky130_d2r.lvs.pvl', M / 'sky130_d2r.lvs.pvl')

# ── 빈 timing 모형
AREA = {'cb_tg_n2': 5.52 * 9.165, 'cb_tgw_n20': 5.52 * 18.165, 'clamp_d2r': 5.115 * 9.80}
PINS = {'cb_tg_n2': [('a', 'inout'), ('b', 'inout'), ('ctl', 'input'), ('ctlb', 'input')],
        'cb_tgw_n20': [('a', 'inout'), ('b', 'inout'), ('ctl', 'input'), ('ctlb', 'input')],
        'clamp_d2r': [('col', 'inout'), ('vrailp', 'inout'), ('vrailm', 'inout')]}
PG = {'cb_tg_n2': ('VDD', 'VSS'), 'cb_tgw_n20': ('VDD', 'VSS'), 'clamp_d2r': (None, 'VSS')}
L = ['/* cb_macros.lib — GENERATED by mk_macros.py: col_blk 매크로의 빈 timing 모형 (핀·용량만) */',
     'library (cb_macros) {', '  delay_model : table_lookup ;', '  time_unit : "1ns" ;', '  voltage_unit : "1V" ;',
     '  current_unit : "1mA" ;', '  capacitive_load_unit (1, pf) ;', '  pulling_resistance_unit : "1kohm" ;',
     '  leakage_power_unit : "1nW" ;', '  nom_process : 1.0 ;', '  nom_voltage : 5.5 ;', '  nom_temperature : 85.0 ;',
     '  voltage_map (VDD, 5.5) ;', '  voltage_map (VSS, 0.0) ;']
for cell, pins in PINS.items():
    L += [f'  cell ({cell}) {{', f'    area : {AREA[cell]:.4f} ;', '    dont_touch : true ;', '    dont_use : true ;',
          '    is_macro_cell : true ;']
    vdd, vss = PG[cell]
    if vdd:
        L += [f'    pg_pin ({vdd}) {{ voltage_name : VDD ; pg_type : primary_power ; }}']
    L += [f'    pg_pin ({vss}) {{ voltage_name : VSS ; pg_type : primary_ground ; }}']
    for pn, d in pins:
        cap = 0.010 if pn in ('ctl', 'ctlb') else 0.005
        L += [f'    pin ({pn}) {{ direction : {d} ; capacitance : {cap} ; }}']
    L += ['  }']
L += ['}', '']
(M / 'cb_macros.lib').write_text('\n'.join(L))
print('macros/:', ' '.join(sorted(p.name for p in M.iterdir())))
