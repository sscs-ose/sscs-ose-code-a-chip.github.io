#!/usr/bin/env python3
"""col_ctrl 합성 netlist (Genus, 평탄) + 매크로 인스턴스 (col_macros.vh, gen_colblk.py) → col_blk netlist (col_blk_syn.v).
col_ctrl 의 출력 (decoder 10 × 64) 은 col_blk 안의 wire 가 되고, 매크로 ctl·ctlb 가 그 wire 에 붙는다.
col_blk 핀: col[63:0] (inout, 배열 쪽), 아날로그 inout vw vbus C1 C2 vzero (덱 node 0) vrailp vrailm,
            디지털 입력 sdi rstb col1_clk col2_clk sel_en PROG VER SENSE WRANY lo (+ 남는 열 SP TG 의 READ READb).
쓰임: python3 merge_netlist.py   (Olympus, run_blk.sbatch 안)
"""
import re
from pathlib import Path

H = Path(__file__).resolve().parent
src = (H / 'col_ctrl_syn.v').read_text()
src = re.sub(r'//.*', '', src)
mods = re.findall(r'\bmodule\s+(\S+?)\s*\(', src)
assert mods == ['col_ctrl'], f'평탄 netlist 가 아님: {mods}'
m = re.search(r'module\s+col_ctrl\s*\((.*?)\);(.*)endmodule', src, re.S)
body = m.group(2)
stmts = [s.strip() for s in body.split(';') if s.strip()]
outs, ins, keep, alias = [], [], [], {}
for s in stmts:
    t = s.split(None, 1)[0]
    if t == 'output':
        outs.append(s)
    elif t == 'input':
        ins.append(s)
    elif t == 'assign':
        a, b = [x.strip() for x in s[len('assign'):].split('=')]
        alias[a] = b
    else:
        keep.append(s)
in_names = set()
for s in ins:
    for n in re.sub(r'^input\s+(\[\d+:\d+\]\s*)?', '', s).split(','):
        in_names.add(n.strip())
want_in = {'sdi', 'rstb', 'col1_clk', 'col2_clk', 'sel_en', 'PROG', 'VER', 'SENSE', 'WRANY', 'lo'}
assert in_names == want_in, in_names


def res(n):                                      # assign 사슬 따라 대표 넷
    seen = set()
    while n in alias:
        assert n not in seen
        seen.add(n); n = alias[n]
    return n


mac = (H / 'col_macros.vh').read_text()
n_rep = 0


def sub(mo):
    global n_rep
    n = mo.group(2)
    r = res(n)
    if r != n:
        n_rep += 1
    return f'.{mo.group(1)}({r})'


mac = re.sub(r'\.(\w+)\(([^)]*)\)', sub, mac)
A = ['vw', 'vbus', 'C1', 'C2', 'vzero', 'vrailp', 'vrailm']
D = ['sdi', 'rstb', 'col1_clk', 'col2_clk', 'sel_en', 'PROG', 'VER', 'SENSE', 'WRANY', 'lo', 'READ', 'READb']
L = ['// col_blk_syn.v — GENERATED by merge_netlist.py (col_ctrl_syn.v + col_macros.vh)',
     f'module col_blk (col, {", ".join(A)}, {", ".join(D)});',
     '  inout [63:0] col;', f'  inout {", ".join(A)};', f'  input {", ".join(D)};']
# ';' 앞에 빈칸: escaped identifier (\\g_col[0].u_coll_n_1 ) 는 빈칸으로 끝난다 — 붙이면 ';' 가 이름에 들어감
L += [f'  {s} ;' for s in keep]
L += [mac.rstrip(), 'endmodule', '']
(H / 'col_blk_syn.v').write_text('\n'.join(L))
n_cells = sum(1 for s in keep if not s.startswith('wire'))
print(f'col_blk_syn.v: std 셀 {n_cells}, 매크로 {mac.count(");")}, assign {len(alias)} 개 (매크로 연결 {n_rep} 곳 바꿈)')
