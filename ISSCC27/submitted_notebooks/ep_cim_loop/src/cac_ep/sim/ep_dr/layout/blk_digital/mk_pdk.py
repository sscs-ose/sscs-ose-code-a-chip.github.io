#!/usr/bin/env python3
"""[layout/blk_digital 사본 10/28: ep_dr/digital/mk_pdk.py 에서 출력 폴더만 blk_digital/pdk 로] hvl 5 V 표준 셀 파일을 blk_digital/pdk/ 로 모은다 (Olympus 로 올릴 묶음).
  - volare sky130A (c6d73a35) libs.ref/sky130_fd_sc_hvl 에서 그대로 복사: lib (ff_085C_5v50), lef, techlef nom, gds, verilog 모형 2 개
  - sky130_fd_sc_hvl_u.cdl: CDL 의 w=/l= 가 단위 없이 적혀 m 로 읽힘 → µm 'u' 를 붙인 사본 (layout/hvl_test.py 와 같은 치환)
    (hvl techlef 은 li1 이 ROUTING 층 = 셀 핀이 li1 이라 배선기가 mcon (L1M1) via 와 li1 패드를 쓴다 → 표에 없으면 GDS 에서 빠짐)
쓰임: python3 mk_pdk.py
"""
import re
import shutil
from pathlib import Path

H = Path(__file__).resolve().parent
LIB = Path('/home/dave/pdk/volare/sky130A/libs.ref/sky130_fd_sc_hvl')
P = H / 'pdk'
P.mkdir(exist_ok=True)
for src in ['lib/sky130_fd_sc_hvl__ff_085C_5v50.lib', 'lef/sky130_fd_sc_hvl.lef', 'techlef/sky130_fd_sc_hvl__nom.tlef',
            'gds/sky130_fd_sc_hvl.gds', 'verilog/primitives.v', 'verilog/sky130_fd_sc_hvl.v']:
    shutil.copy2(LIB / src, P / Path(src).name)
cdl = (LIB / 'cdl' / 'sky130_fd_sc_hvl.cdl').read_text()
cdl_u, n = re.subn(r'\b([wl])=([0-9.]+)(?=\s)', r'\1=\2u', cdl)
(P / 'sky130_fd_sc_hvl_u.cdl').write_text(cdl_u)

M = ['# sky130_hvl_stream.map — GENERATED by mk_pdk.py (ep_demo sky130_stream.mapFile + li1·mcon)', '']
for lyr, num in (('li1', 67), ('met1', 68), ('met2', 69), ('met3', 70), ('met4', 71), ('met5', 72)):
    M += [f'{lyr:6s}  {k:9s} {num}  {dt}' for k, dt in (('net', 20), ('spnet', 20), ('lefobs', 20), ('via', 20),
                                                          ('pin', 16), ('lefpin', 16), ('blockage', 10), ('text', 5))]
    M += [f'name    {lyr}/pin  {num}  5', '']
for cut, num in (('mcon', 67), ('via', 68), ('via2', 69), ('via3', 70), ('via4', 71)):
    M += [f'{cut:6s}  {k:9s} {num}  44' for k in ('net', 'spnet', 'via', 'lefobs')]
    M += [f'{cut:6s}  {k:9s} {num}  58' for k in ('pin', 'lefpin')] + ['']
(P / 'sky130_hvl_stream.map').write_text('\n'.join(M) + '\n')
print(f'pdk/: 복사 6 개, CDL w/l 단위 {n} 곳, 층 표 {sum(1 for x in M if x and not x.startswith("#"))} 줄')
