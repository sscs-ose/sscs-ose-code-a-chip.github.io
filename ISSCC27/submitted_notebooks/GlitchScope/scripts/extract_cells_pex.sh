#!/bin/bash
# Parasitic-extracted SPICE netlists of the SKY130 HD cells GlitchScope uses, from the PDK's own
# cell layouts (GDS) with Magic and the PDK's Magic tech file: transistor source/drain diffusion
# areas and perimeters plus every intra-cell coupling and ground capacitance.
#
# Why: the PDK's cell SPICE library (libs.ref/sky130_fd_sc_hd/spice) is schematic-level -- it has
# no diffusion areas and no wiring capacitance -- while the Liberty tables were characterised on
# extracted cells.  On dfxtp_1 the schematic netlist draws 17.9 fJ per idle clock cycle, the
# extracted one 33.8 fJ; Liberty says 40.5 fJ.
#
#   scripts/extract_cells_pex.sh      -> data/pdk/pex/sky130_fd_sc_hd_pex.spice
# Use it in every ngspice run with GS_CELL_SPICE=data/pdk/pex/sky130_fd_sc_hd_pex.spice
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
[ -f "$ROOT/tools.env" ] && set -a && . "$ROOT/tools.env" && set +a
export PDK_ROOT=$(dirname "$GS_PDK_ROOT")
CELLS="a21oi_1 a22oi_1 and2_1 buf_1 inv_1 nand2_1 nand3_1 nor2_1 o21ai_0 or2_1 xnor2_1 xor2_1 dfxtp_1"
# cells that OpenROAD adds to the routed multiplier layouts (clock tree, resizer buffers): post-layout SPICE.
# (The committed file keeps the first 13 cells exactly as first extracted; re-extraction reproduces them up to the
# order of capacitor elements.)
CELLS="$CELLS buf_4 bufinv_16 clkbuf_1 clkbuf_8 clkbuf_16 clkdlybuf4s50_1 clkinv_2 clkinv_4 clkinvlp_4 inv_6 inv_8"
OUT=$ROOT/data/pdk/pex; mkdir -p "$OUT"; W=$(mktemp -d)
{
  echo "gds readonly true"
  echo "gds read $GS_PDK_ROOT/libs.ref/sky130_fd_sc_hd/gds/sky130_fd_sc_hd.gds"
  for c in $CELLS; do
    echo "load sky130_fd_sc_hd__$c"
    echo "select top cell"
    echo "extract style ngspice()"
    echo "extract do local"
    echo "extract all"
    echo "ext2spice lvs"
    echo "ext2spice cthresh 0"
    echo "ext2spice -o $W/$c.spice"
  done
  echo "quit -noprompt"
} > "$W/ex.tcl"
(cd "$W" && "$GS_MAGIC_TCL" -dnull -noconsole -rcfile "$GS_PDK_ROOT/libs.tech/magic/sky130A.magicrc" ex.tcl > magic.log 2>&1)
{
  echo "* SKY130 HD standard cells, parasitic-extracted with Magic from the SKY130 PDK cell layouts"
  echo "* (Apache-2.0, SkyWater/Google).  Generated by scripts/extract_cells_pex.sh; units: um (.option scale=1e-6)."
  for c in $CELLS; do
    grep -v '^\*\|^\.end$\|^$' "$W/$c.spice"
    echo
  done
} > "$OUT/sky130_fd_sc_hd_pex.spice"
grep -c '^\.subckt' "$OUT/sky130_fd_sc_hd_pex.spice" | xargs echo "cells extracted:"
rm -rf "$W"
