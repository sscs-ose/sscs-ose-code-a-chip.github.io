#!/bin/bash
# RTL/netlist -> placed & routed SKY130 HD layout with OpenROAD-flow-scripts (ORFS),
# then post-layout glitch analysis (GlitchScope with SPEF wire capacitance) and
# OpenSTA power with GlitchScope's glitch-accurate SAIF.
#
#   scripts/layout_flow.sh <variant> [n_cycles]
#
# <variant> is v0 | v1 | v2 (hand-made pipelines, below) or any name whose netlist is
# bench/layout/mul16_<variant>.v (e.g. the GlitchFix outputs r_ga / r_td, see
# scripts/glitchfix_layout.sh); a missing ORFS config is created from v0's.
#
# Needs in tools.env (or the environment): GS_ORFS (ORFS checkout), GS_OPENROAD,
# GS_YOSYS, GS_STA, GS_LIB.  The variants are generated by
#   python bench/gen_arraymul.py 16 bench/layout/mul16_v0.v --regs --name mul16
#   python bench/gen_arraymul.py 16 bench/layout/mul16_v1.v --pipe 3 --name mul16
#   python bench/gen_arraymul.py 16 bench/layout/mul16_v2.v --pipe 9 --name mul16
set -euo pipefail
V=${1:?variant}; N=${2:-40}
# DESIGN (module name, default mul16) and PERIOD_PS (default 15000) select another design:
# netlist bench/layout/${DESIGN}_<variant>.v, SDC bench/layout/orfs/constraint_${DESIGN}.sdc if present
DESIGN=${DESIGN:-mul16}; PERIOD_PS=${PERIOD_PS:-15000}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
[ -f "$ROOT/tools.env" ] && set -a && . "$ROOT/tools.env" && set +a
export GLITCHSCOPE_ROOT=$ROOT
export YOSYS_EXE=$GS_YOSYS OPENROAD_EXE=$GS_OPENROAD
export LD_LIBRARY_PATH=$(dirname "$GS_STA")/../../sta_deps/lib:${LD_LIBRARY_PATH:-}
export TCL_LIBRARY=${TCL_LIBRARY:-$(dirname "$GS_STA")/../../sta_deps/lib/tcl8.6}
WORK=$ROOT/build_layout
CFG=$ROOT/bench/layout/orfs/$V/config.mk
if [ ! -f "$CFG" ]; then
  mkdir -p "$(dirname "$CFG")"
  SDC=constraint.sdc; [ -f "$ROOT/bench/layout/orfs/constraint_$DESIGN.sdc" ] && SDC=constraint_$DESIGN.sdc
  sed -e "s/mul16_v0/${DESIGN}_$V/g" -e "s/DESIGN_NAME     = mul16/DESIGN_NAME     = $DESIGN/" \
      -e "s#orfs/constraint.sdc#orfs/$SDC#" \
      -e "s/variant v0.*/variant $V of $DESIGN (generated by layout_flow.sh)/" \
      "$ROOT/bench/layout/orfs/v0/config.mk" > "$CFG"
fi
RES=$WORK/results/sky130hd/${DESIGN}_$V/base
OUT=$ROOT/data/layout/$V
mkdir -p "$OUT"

echo "== [$V] ORFS: synth -> floorplan -> place -> CTS -> route -> finish"
make -C "$GS_ORFS/flow" DESIGN_CONFIG="$CFG" WORK_HOME="$WORK" \
     "$RES/6_final.v" "$RES/6_final.def" >"$OUT/orfs.log" 2>&1 || { tail -40 "$OUT/orfs.log"; exit 1; }

echo "== [$V] GlitchScope post-layout (SPEF wire capacitance, $N random cycles @ $PERIOD_PS ps)"
python3 -m glitchscope.flow --netlist "$RES/6_final.v" --spef "$RES/6_final.spef" --lib "$GS_LIB" \
        --random-vectors "$N" --period-ps "$PERIOD_PS" --seed 3 --no-attribution --out "$OUT/glitchscope" | sed -n '1,6p'

echo "== [$V] OpenSTA power: vectorless vs GlitchScope SAIF"
cat > "$OUT/power.tcl" <<EOF
read_liberty $GS_LIB
read_verilog $RES/6_final.v
link_design $DESIGN
read_sdc $RES/6_final.sdc
read_spef $RES/6_final.spef
set_propagated_clock [all_clocks]
puts "===== vectorless (default activity)"
report_power
read_saif -scope $DESIGN $OUT/glitchscope/glitch_activity.saif
puts "===== with GlitchScope SAIF"
report_power
report_checks -path_delay max -digits 3
report_design_area
EOF
"$GS_STA" -no_splash -exit "$OUT/power.tcl" >"$OUT/power.log" 2>&1 || true
grep -E "=====|^Total|Annotated|slack|Design area" "$OUT/power.log" | head -20
cp "$RES/6_final.v" "$RES/6_final.def" "$OUT/" 2>/dev/null || true
gzip -f "$OUT/6_final.def"
